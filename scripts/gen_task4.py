MW, X0, RH_SUB, LANE_PAD = 112, 240, 46, 12


def month_range(start, dur):
    a = int(math.floor(start + 1e-9)) + 1
    b = int(math.ceil(start + dur - 1e-9))
    return "M%d–M%d" % (a, b) if a != b else "M%d" % a


def roadmap():
    # раскладка по подстрокам внутри дорожек
    lane_rows = []
    placed = {}
    for li in range(len(LANES)):
        items = sorted([t for t in TASKS if t[1] == li], key=lambda t: t[4])
        rows_end = []
        for t in items:
            for r, e in enumerate(rows_end):
                if e <= t[4] + 1e-9:
                    rows_end[r] = t[4] + t[5]
                    placed[t[0]] = r
                    break
            else:
                rows_end.append(t[4] + t[5])
                placed[t[0]] = len(rows_end) - 1
        lane_rows.append(max(1, len(rows_end)))
    H_HEAD = 110
    total_h = H_HEAD + sum(n * RH_SUB + LANE_PAD for n in lane_rows) + 120
    W = X0 + MW * 12 + 30
    d = Diagram("RoadMap", W, total_h)
    d.text("title", 20, 6, 1500, 26, "RoadMap: MVP на горизонте 6 месяцев и целевое решение на горизонте года", size=15, bold=True)
    # кварталы
    for q in range(4):
        d.box("q%d" % q, X0 + q * 3 * MW, 40, 3 * MW - 4, 30, "Q%d" % (q + 1), fill="#f5f5f5", stroke="#666666",
              size=12, bold=True, shape="chevron")
    for m in range(12):
        d.box("m%d" % m, X0 + m * MW, 74, MW - 4, 24, "M%d" % (m + 1), fill="#ffffff", stroke="#cccccc", size=10)
    # дорожки
    y = H_HEAD
    lane_y = []
    for li, name in enumerate(LANES):
        h = lane_rows[li] * RH_SUB + LANE_PAD
        lane_y.append((y, h))
        d.box("ln%d" % li, 20, y, X0 - 28, h - 6, name, fill="#f5f5f5", stroke="#666666", size=10, bold=True)
        d.box("lb%d" % li, X0, y, MW * 12 - 4, h - 6, "", fill="#fff2cc", stroke=None, rounded=False)
        y += h
    colors = {"mvp": ("#ffe6cc", "#d79b00"), "rate": ("#d5e8d4", "#82b366"), "goal": ("#dae8fc", "#6c8ebf")}
    for t in TASKS:
        tid, li, name, _, st, dur, _, grp = t
        ly, lh = lane_y[li]
        x = X0 + st * MW + 2
        w = dur * MW - 6
        yy = ly + 6 + placed[tid] * RH_SUB
        f, s = colors[grp]
        d.box(tid, x, yy, w, RH_SUB - 6, "%s – %s" % (tid, name), fill=f, stroke=s, size=9, rounded=False, align="left")
    top, bottom = H_HEAD - 8, y
    d.line(X0 + 6 * MW - 2, top, X0 + 6 * MW - 2, bottom, color="#cc0000", width=2)
    d.line(X0 + 12 * MW - 4, top, X0 + 12 * MW - 4, bottom, color="#cc0000", width=2)
    d.text("ms1", X0 + 6 * MW - 150, bottom + 4, 300, 22, "▲ Конец M6: MVP", size=11, bold=True, color="#cc0000", align="center")
    d.text("ms2", X0 + 12 * MW - 320, bottom + 4, 316, 22, "▲ Конец M12: целевое состояние", size=11, bold=True, color="#cc0000", align="right")
    # легенда
    ly = bottom + 36
    d.text("lgt", 20, ly, 100, 22, "Легенда:", size=11, bold=True)
    for i, (k, lab) in enumerate([("mvp", "MVP (первые 6 месяцев)"), ("rate", "Передача ставок в кол-центры (Задание 4)"),
                                  ("goal", "Целевое состояние (до конца года)")]):
        f, s = colors[k]
        d.box("lg" + k, 100 + i * 330, ly, 320, 26, lab, fill=f, stroke=s, size=10, rounded=False)
    d.save(OUT, "RoadMap")


