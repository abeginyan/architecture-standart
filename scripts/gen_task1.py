"""Task1: карта IT-ландшафта (оргструктура x бизнес-возможности) и схема интеграции приложений."""
import os
from diagramkit import Diagram

OUT = os.path.join(os.path.dirname(__file__), "..", "Task1")

# цвета систем
C = {
    "abs": ("#f8cecc", "#b85450"),      # АБС
    "ib": ("#dae8fc", "#6c8ebf"),       # интернет-банк
    "site": ("#d5e8d4", "#82b366"),     # сайт
    "cc": ("#fff2cc", "#d6b656"),       # система кол-центра
    "pcc": ("#e1d5e7", "#9673a6"),      # партнёрский кол-центр
    "sms": ("#ffe6cc", "#d79b00"),      # СМС-шлюз
    "man": ("#ffffff", "#666666"),      # ручной обмен (почта/Excel)
}

# ---------------------------------------------------------------- 1. Карта IT-ландшафта
def landscape_map():
    cols = [
        ("Продажи в сети\nотделений", "Продажи и маркетинг"),
        ("Продажи через\nкол-центр", "Продажи и маркетинг"),
        ("Digital-оповещения\nклиентов", "Продажи и маркетинг"),
        ("Обслуживание\nдепозитных процессов", "Поддержка операционных процессов"),
        ("Обслуживание\nкредитных процессов", "Поддержка операционных процессов"),
        ("Управление\nдоговорами", "Поддержка операционных процессов"),
        ("Онлайн-каналы\n(добавлена: в исходной карте возможностей её нет)", "Добавлено к карте возможностей"),
    ]
    rows = [
        ("Управление обслуживанием в сети отделений\n(фронт-офис, 50 отделений, 500 чел.)", {
            0: [("abs", "АБС (десктоп-клиент Delphi)")],
            3: [("man", "Эл. почта (запрос ставки у бэк-офиса)")],
            5: [("abs", "АБС (создание депозита, загрузка документов)")],
        }),
        ("Кол-центр банка\n(200 операторов; платформа подрядчика)", {
            1: [("cc", "Система кол-центра (React / Java Spring Boot / PostgreSQL)")],
            3: [("cc", "Система кол-центра: обращение по депозиту"), ("abs", "→ передаётся в АБС")],
        }),
        ("Партнёрский кол-центр\n(внешняя компания, 100 чел.)", {
            1: [("pcc", "Система партнёрского кол-центра (внешняя; работа по готовым скриптам)")],
        }),
        ("Управление депозитными продуктами\n(бэк-офис, 50 чел.)", {
            2: [("abs", "АБС → СМС-шлюз (СМС клиенту со ставкой)")],
            3: [("abs", "АБС (обработка заявки, ставка)"), ("man", "Excel (расчёт ставок) + почта")],
            5: [("abs", "АБС")],
        }),
        ("Управление кредитными продуктами\n(бэк-офис, 50 чел.)", {
            3: [("man", "Эл. почта (данные о кредитном риске)")],
            4: [("abs", "АБС (кредитный раздел)")],
        }),
        ("IT-отдел\n(АБС — 20 чел.; интернет-банк — 10 + 10 подрядчик)", {
            2: [("sms", "СМС-шлюз (поддержка, связь с оператором)"), ("ib", "Интернет-банк (ядро: СМС-коды)")],
            5: [("abs", "АБС (разработка внутри банка)")],
            6: [("ib", "Интернет-банк (платежи, тек. счета)"), ("site", "Сайт (PHP + React.js)")],
        }),
        ("Команда цифровой трансформации\nрозничного бизнеса (10 чел.)", {
            6: [("ib", "Интернет-банк — развитие продукта"), ("site", "Сайт — развитие продукта")],
        }),
    ]
    LEFT, TOPH1, TOPH2 = 300, 70, 60
    CW, RH = 235, 118
    W = 20 + LEFT + CW * len(cols) + 20
    H = 40 + TOPH1 + TOPH2 + RH * len(rows) + 120
    d = Diagram("Карта IT-ландшафта", W, H)
    d.text("title", 20, 8, 1500, 28, "Карта текущего IT-ландшафта банка «Стандарт»: оргструктура × бизнес-возможности 2-го уровня",
           size=15, bold=True)
    y0 = 44
    # уровень 1 (группы)
    groups = {}
    for i, (_, g) in enumerate(cols):
        groups.setdefault(g, []).append(i)
    for g, idxs in groups.items():
        x = 20 + LEFT + CW * idxs[0]
        w = CW * len(idxs) - 6
        col = "#1f55cc" if "Добавлено" not in g else "#999999"
        d.box("g_" + g, x, y0, w, TOPH1 - 6, g, fill=col, stroke=col, color="#ffffff", size=14, bold=True)
    for i, (name, g) in enumerate(cols):
        x = 20 + LEFT + CW * i
        gap = "Добавлено" in g
        d.box("c%d" % i, x, y0 + TOPH1, CW - 6, TOPH2 + 6, name, fill="#e8f0ff" if not gap else "#f2f2f2",
              stroke="#1f55cc" if not gap else "#999999", size=11, bold=True, dashed=gap)
    d.box("corner", 20, y0, LEFT - 6, TOPH1 + TOPH2 + 6, "Элементы оргструктуры\n(строки)  ↓            Бизнес-возможности (колонки)  →",
          fill="#f5f5f5", stroke="#999999", size=11, bold=True)
    yy = y0 + TOPH1 + TOPH2 + 12
    for r, (rname, cells) in enumerate(rows):
        y = yy + RH * r
        d.box("r%d" % r, 20, y, LEFT - 6, RH - 6, rname, fill="#dae8fc", stroke="#6c8ebf", size=11, bold_first=True)
        for ci in range(len(cols)):
            x = 20 + LEFT + CW * ci
            gap = ci == len(cols) - 1
            d.box("cell%d_%d" % (r, ci), x, y, CW - 6, RH - 6, "", fill="#f4f4f4" if not gap else "#fafafa",
                  stroke="#dddddd", dashed=gap)
            items = cells.get(ci, [])
            if not items:
                continue
            ih = min(34, (RH - 16) // len(items) - 3 if len(items) > 1 else 56)
            ih = max(ih, 30)
            for k, (key, label) in enumerate(items):
                f, s = C[key]
                d.box("s%d_%d_%d" % (r, ci, k), x + 6, y + 6 + k * (ih + 4) + (0 if len(items) > 1 else (RH - 12 - ih) / 2 - 3),
                      CW - 18, ih, label, fill=f, stroke=s, size=10, dashed=(key == "man"))
    # легенда
    ly = yy + RH * len(rows) + 6
    d.text("lg", 20, ly, 200, 20, "Легенда:", size=11, bold=True)
    items = [("abs", "АБС (собственная разработка)"), ("ib", "Интернет-банк (платформа подрядчика)"),
             ("site", "Сайт (собственная разработка)"), ("cc", "Система кол-центра (подрядчик)"),
             ("pcc", "Система партнёрского кол-центра (внешняя)"), ("sms", "СМС-шлюз"),
             ("man", "Ручной обмен: Excel / эл. почта")]
    x = 100
    for key, lab in items:
        f, s = C[key]
        d.box("lg_" + key, x, ly + 24, 195, 34, lab, fill=f, stroke=s, size=9, dashed=(key == "man"))
        x += 203
    d.text("note", 20, ly + 64, W - 40, 36,
           "Пустая ячейка = для этой возможности у подразделения нет собственной IT-системы. "
           "Последняя колонка добавлена к карте возможностей, потому что интернет-банк и сайт не ложатся ни в одну из шести исходных возможностей.",
           size=10, color="#555555")
    d.save(OUT, "IT_landscape_map")


# ---------------------------------------------------------------- 2. Схема интеграции
def integration_scheme():
    d = Diagram("Схема интеграции приложений", 1800, 1080)
    d.text("title", 20, 8, 1700, 28, "Текущая схема интеграции приложений и участников процессов (процесс открытия депозита)",
           size=15, bold=True)
    P = dict(fill="#08427B", stroke="#073b6f", color="#ffffff", size=11, bold_first=True)

    def person(id, x, y, w, h, t):
        d.box(id, x, y, w, h, t, **P)

    def system(id, x, y, w, h, key, t):
        f, s = C[key]
        d.box(id, x, y, w, h, t, fill=f, stroke=s, size=10, bold_first=True)

    # участники
    person("client", 30, 200, 190, 90, "Клиент\n(в основном старшего возраста)")
    person("branch", 390, 370, 210, 64, "Сотрудник отделения\n(фронт-офис)")
    person("ccop", 390, 560, 210, 64, "Оператор кол-центра банка")
    person("pccop", 390, 760, 210, 64, "Оператор партнёрского кол-центра")
    person("biz", 390, 900, 210, 64, "Бизнес-представители банка")
    person("dep", 1000, 70, 250, 64, "Менеджер бэк-офиса депозитов")
    person("cred", 1400, 70, 250, 64, "Сотрудник отдела кредитования")
    # системы
    system("site", 390, 70, 210, 80, "site", "Сайт\nPHP + React.js\nтолько маркетинговая информация")
    system("ib", 390, 200, 210, 100, "ib", "Интернет-банк\nASP.NET MVC / .NET Fw 4.5, MS SQL\nмонолит, платформа подрядчика;\nплатежи и открытие тек. счетов")
    system("cc", 740, 620, 210, 100, "cc", "Система кол-центра\nReact / Java Spring Boot / PostgreSQL\nмикросервисы, платформа подрядчика")
    system("pcc", 760, 760, 210, 80, "pcc", "Система партнёрского кол-центра\n(внешняя информационная система)")
    system("abs", 1000, 340, 300, 200, "abs", "АБС\nDelphi-клиент + Oracle (логика на PL/SQL)\nучёт операций, бухгалтерия,\nдепозиты и кредиты (разные разделы)")
    system("mail", 700, 200, 230, 80, "man", "Эл. почта + Excel-файл расчёта ставок\n(ручной обмен, ставки нигде больше не ведутся)")
    system("sms", 1000, 700, 230, 80, "sms", "СМС-шлюз\nподдерживает IT-отдел банка")
    d.box("tel", 1400, 700, 230, 80, "Телеком-оператор\n(внешний, отправка СМС)", fill="#f5f5f5", stroke="#666666", size=10, bold_first=True)

    # связи
    d.edge("client", "site", "1. смотрит маркетинговую информацию")
    d.edge("client", "ib", "2. платежи, тек. счета")
    d.edge("ib", "abs", "прямое подключение к БД Oracle", bidir=True)
    d.edge("client", "branch", "3. личный визит: заявка на депозит", bidir=True)
    d.edge("branch", "abs", "4. создаёт депозит, загружает документы", bidir=True)
    d.edge("client", "ccop", "5. звонок перед визитом")
    d.edge("ccop", "cc", "6. заводит обращение")
    d.edge("cc", "abs", "7. обращение → АБС")
    d.edge("dep", "abs", "8. определяет ставку, обрабатывает заявку")
    d.edge("abs", "sms", "9. СМС о ставке")
    d.edge("sms", "tel", "10. отправка СМС")
    d.edge("tel", "client", "11. СМС клиенту: «приходите за депозитом»", dashed=True, via=[(1515, 1010), (125, 1010)])
    d.edge("branch", "mail", "12. запрос ставки (письмо)", dashed=True)
    d.edge("cred", "mail", "13. данные о кредитном риске\n(письмо, ежедневно Excel)", dashed=True)
    d.edge("dep", "mail", "14. считает ставку в Excel", dashed=True)
    d.edge("cred", "abs", "15. анализирует риск в своём разделе АБС")
    d.edge("biz", "pccop", "16. передают готовые скрипты звонков", dashed=True)
    d.edge("client", "pccop", "17. звонок (при подключении партнёра)", dashed=True)
    d.edge("pccop", "pcc", "18. работает в ней")

    # легенда
    d.box("lg1", 1300, 900, 210, 34, "Участники процесса (люди)", **dict(P, bold_first=False, size=10))
    for i, (k, t) in enumerate([("abs", "Собственные системы банка"), ("ib", "Системы подрядчиков"),
                                ("pcc", "Внешние системы"), ("man", "Ручной обмен (пунктир)")]):
        f, s = C[k]
        d.box("lg_" + k, 1530 if i % 2 == 0 else 1530, 900 + i * 40, 230, 34, t, fill=f, stroke=s, size=10,
              dashed=(k == "man"))
    d.text("lgt", 1300, 945, 220, 60, "Сплошная линия — автоматизированное взаимодействие, пунктир — ручной обмен или внешний канал.",
           size=9, color="#555555")
    d.save(OUT, "Integration_scheme")


if __name__ == "__main__":
    landscape_map()
    integration_scheme()
    print("Task1 готов")
